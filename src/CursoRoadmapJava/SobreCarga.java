package CursoRoadmapJava;

public class SobreCarga {

    // 1ra versión: Suma de DOS números enteros (int)
    public int suma(int a, int b) {
        return a + b;
    }

    // 2da versión: Suma de TRES números enteros (int)
    public int suma(int a, int b, int c) {
        return a + b + c;
    }

    // 3ra versión: Suma de TRES números decimales (double)
    public double suma(double a, double b, double c) {
        return a + b + c;
    }
}